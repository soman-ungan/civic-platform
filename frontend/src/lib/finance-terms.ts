export type TermKind = "purpose" | "revenue" | "nature" | "indicator";

const TERMS: Record<TermKind, Record<string, string>> = {
  purpose: PURPOSE,
  revenue: REVENUE,
  nature: NATURE,
  indicator: INDICATOR,
};

/** 費目の説明。無ければ null（ⓘ を出さない） */
export function termNote(kind: TermKind, key: string): string | null {
  const note = TERMS[kind][key];
  if (note) return note;
  // 県が集めた税を市町村に分ける交付金（利子割交付金・法人事業税交付金など）。年度で種類が変わる
  if (kind === "revenue" && key.endsWith("交付金") && /割|税/.test(key)) {
    return "県が集めた税の一部を、市町村に分けてもらうもの";
  }
  return null;
}

